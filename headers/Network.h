/**
 * @brief Central class managing all components of the traffic network.
 */

#pragma once
// Libraries
#include <array>  // To use arrays
#include <deque>  // To use deques
#include <list>   // To use lists
#include <memory> // To use smart pointers
#include <random> // To use std::mt19937
#include <vector> // To use vectors
// Header files
#include "Intersection.h"
#include "IntersectionOperator.h"
#include "Road.h"
#include "Map.h"

// Forward declaration
struct GLFWwindow;

/** @brief Traffic measured since the start of the simulation (or the last Network::resetStats()).
 * Times are in simulated seconds. */
struct TrafficStats {
   /** Duration of the measure. */
   double duration = 0.0;
   /** Vehicles generated by the demand. */
   int generated = 0;
   /** Vehicles generated but dropped because too many vehicles were already waiting outside. */
   int rejected = 0;
   /** Vehicles that entered the network. */
   int entered = 0;
   /** Vehicles that reached their destination. */
   int completed = 0;
   /** Time spent by all the vehicles, in the network or waiting to enter it, in vehicle.seconds.
    * Unlike the travel times, it also counts the vehicles that did not arrive. */
   double timeSpent = 0.0;
   /** Time spent in the network by all the vehicles, in vehicle.seconds. */
   double timeInNetwork = 0.0;
   /** Time spent waiting (almost stopped) in the network by all the vehicles, in vehicle.seconds. */
   double timeWaiting = 0.0;
   /** Sum over time and vehicles in the network of speed / maximum speed, in vehicle.seconds. */
   double relativeSpeedTime = 0.0;
   /** Largest number of vehicles waiting on one road. */
   int maxQueue = 0;
   /** Travel time (since generated) of each vehicle that reached its destination. */
   std::vector<float> travelTimes;
   /** Sum of the travel times without traffic nor traffic lights of the same vehicles. */
   double freeFlowTime = 0.0;

   /** @returns Completed trips per minute */
   double flow() const;
   /** @returns Average travel time of the completed trips */
   double meanTravelTime() const;
   /** @returns Average time lost per completed trip, compared to an empty network without lights */
   double meanDelay() const;
   /** @param ratio In [0, 1], e.g. 0.95 for the 95th percentile
    * @returns Travel time not exceeded by this ratio of the completed trips */
   double travelTimePercentile(double ratio) const;
   /** @returns Time spent per generated vehicle, arrived or not. With the same demand, the
    * lower the better: a controller cannot improve it by leaving vehicles behind. */
   double timeSpentPerVehicle() const;
   /** @returns Average number of vehicles waiting in the network */
   double meanQueue() const;
   /** @returns Average number of vehicles in the network */
   double meanVehicles() const;
   /** @returns Average speed of the vehicles in the network, relative to their maximum speed */
   double meanRelativeSpeed() const;
};

class Network {
public:
   /** @brief Default constructor.
    * @returns Network */
   Network();
   /** @brief Constructor with a fixed random seed (reproducible network and traffic).
    * @param seed Random seed */
   explicit Network(unsigned int seed);
   /** @brief Use one of the built-in controllers for every intersection.
    * @param type Controller type */
   void setController(ControllerType type);
   /** @brief Use a custom controller for every intersection.
    * @param op Controller */
   void setOperator(std::shared_ptr<IntersectionOperator> op);
   /** @brief Print the whole control panel in the terminal (every 5 s) instead of a one-line summary.
    * @param enabled Full terminal output? */
   void setTerminalOutput(bool enabled);
   /** @brief Print the panel values in the terminal. */
   void printTerminalOutput(double smoothedFlowPerMin, double smoothedAvgSpeed, int lastFPS,
                            double elapsedSimulationMinutes) const;
   /** @brief Network display (opens a window and runs the simulation in real time).
    * @param maxFrames Optional parameter restricting total frames to process for the tests (0 = infinite). */
   void displayNetwork(int maxFrames = 0);
   /** @brief Advance the simulation by one fixed time step. Does not need a window / OpenGL context. */
   void step();
   /** @brief Getter.
    * @returns Elapsed simulation time in seconds */
   double getSimulationTime() const;
   /** @brief Getter.
    * @returns Number of vehicles that reached their destination */
   int getCompletedVehicles() const;
   /** @brief Getter.
    * @returns Traffic statistics since the start or the last resetStats() */
   const TrafficStats& getStats() const;
   /** @brief Start a new measure of the traffic statistics. */
   void resetStats();
   /** @brief Getter.
    * @returns Number of vehicles generated and waiting to enter the network */
   int getWaitingVehicleCount() const;
   /** @brief Getter.
    * @returns Number of vehicles currently in the network */
   int getVehicleCount() const;
   /** @brief Getter.
    * @returns Number of roads */
   int getRoadCount() const;
   /** @brief Getter.
    * @returns Number of intersections */
   int getIntersectionCount() const;
   /** @brief Getter.
    * @param id Intersection ID
    * @returns Intersection, nullptr if the ID is not valid */
   const Intersection* getIntersection(int id) const;
   /** @brief Getter.
    * @returns Roads */
   const std::vector<std::unique_ptr<Road>>& getRoads() const;
   /** Duration of one simulation step in seconds (the simulation runs at a fixed rate, independent of the FPS). */
   static constexpr double timeStep{ constants::timeStep };

protected:

private:
   /** @brief Helper to initialize the window and ImGui. */
   GLFWwindow* initWindowAndImGui();
   /** @brief Process and update the metrics. */
   void processMetrics(double currentTime, double& lastTime, int& nbFrames, int& lastFPS);
   /** @brief Render the control panel. */
   void renderControlPanel(int lastFPS, double& lastPrintTime, double currentTime);
   /** @brief Draw roads, vehicles, intersections and traffic lights. */
   void render() const;
   /** Built-in controllers, created when first used. Shared by all the intersections. */
   std::array<std::shared_ptr<IntersectionOperator>, 6> controllers;
   /** Controller currently used by all the intersections. */
   std::shared_ptr<IntersectionOperator> globalOperator;
   /** Random seed. */
   const unsigned int seed;
   /** Random number generator of the traffic demand. It is not used for anything else, so that
    * the same seed gives the same demand whatever the controller does. */
   std::mt19937 demandRng;
   /** Is the simulation paused? */
   bool isPaused = false;
   /** Print the whole control panel in the terminal? */
   bool terminalOutput = false;
   /** Road Map. */
   Map map;
   /** Intersections. */
   std::vector<std::unique_ptr<Intersection>> Intersections;
   /** Roads. */
   std::vector<std::unique_ptr<Road>> Roads;
   /** Vehicles */
   std::list<std::shared_ptr<Vehicle>> Vehicles;
   /** A vehicle generated by the demand, not in the network yet. */
   struct Trip {
      double creationTime;
      Road* origin;
      Intersection* destination;
      int vehicleType;
   };
   /** Vehicles waiting to enter the network, oldest first. */
   std::deque<Trip> waitingTrips;
   /** Simulation time of the next vehicle generation. Negative: not drawn yet. */
   double nextArrivalTime = -1.0;
   /** Demand used to draw nextArrivalTime. */
   double arrivalDemand = 0.0;
   /** @brief Generate the vehicles of the traffic demand for this step (Poisson arrivals). */
   void generateDemand();
   /** @brief Let the waiting vehicles enter the network where there is room. */
   void addVehicles();
   /** @brief Move the Vehicle for the next frame. */
   void updateVehiclesPosition();
   /** @brief Measure the traffic of this step. */
   void updateStats();
   /** Traffic statistics. */
   TrafficStats stats;
   /** Flow and average speed displayed in the panel (smoothed). */
   double smoothedFlowPerMin = 0.0, smoothedAvgSpeed = 0.0;
   /** Simulation time and completed trips at the last flow measure. */
   double lastFlowTime = 0.0;
   int lastFlowCompleted = 0;
   /** Number of completed trips. */
   int completedVehicles = 0;
   /** Identifier given to the next spawned vehicle. */
   int nextVehicleId = 0;
   /** Elapsed simulation time in seconds. */
   double simulationTime = 0.0;
};
